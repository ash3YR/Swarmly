"""Service for generating LangGraph code from graph configurations."""

import re

from src.models.graph import (
    EdgeConfig,
    GraphRequest,
    LLMProvider,
    NodeConfig,
    NodeType,
    ToolName,
)


def _safe_id(node_id: str) -> str:
    """Convert a ReactFlow node ID into a valid Python identifier."""
    # Replace non-alphanumeric characters with underscores
    safe = re.sub(r"\W|^(?=\d)", "_", node_id)
    return safe


def generate_langgraph_code(request: GraphRequest) -> str:
    """Generate the complete, runnable LangGraph Python script."""
    nodes = request.nodes
    edges = request.edges
    
    # Analyze the graph to determine required imports and setup
    used_providers = {node.provider for node in nodes if node.provider}
    used_tools = {node.tool_name for node in nodes if node.tool_name}
    
    has_llm_nodes = any(node.type == NodeType.LLM_AGENT for node in nodes)
    has_tools = len(used_tools) > 0
    
    # Track node connections
    node_out_edges = {}
    node_in_edges = {}
    for edge in edges:
        node_out_edges.setdefault(edge.source, []).append(edge.target)
        node_in_edges.setdefault(edge.target, []).append(edge.source)
        
    # Find tool nodes connected to each LLM node
    llm_to_tools = {}
    for node in nodes:
        if node.type == NodeType.LLM_AGENT:
            llm_to_tools[node.id] = []
            for target_id in node_out_edges.get(node.id, []):
                target_node = next((n for n in nodes if n.id == target_id), None)
                if target_node and target_node.type == NodeType.TOOL:
                    llm_to_tools[node.id].append(target_node)

    imports_section = _generate_imports(used_providers, used_tools, has_tools)
    state_section = _generate_state_schema()
    tools_section, tool_vars = _generate_tools(nodes)
    nodes_section = _generate_nodes(nodes, llm_to_tools, tool_vars)
    graph_section = _generate_graph_construction(nodes, edges, node_in_edges, tool_vars)
    main_section = _generate_main_block()

    sections = [
        f'"""Generated by Swarmly for Agent: {request.agent_name}"""',
        "# -- Imports --",
        imports_section,
        "# -- State Schema --",
        state_section,
    ]
    
    if tools_section:
        sections.extend(["# -- Tools --", tools_section])
        
    sections.extend([
        "# -- Nodes --",
        nodes_section,
        "# -- Graph Construction --",
        graph_section,
        "# -- Entry Point --",
        main_section,
    ])

    return "\n\n".join(filter(None, sections))


def _generate_imports(
    used_providers: set[LLMProvider],
    used_tools: set[ToolName],
    has_tools: bool,
) -> str:
    """Generate the imports block."""
    imports = [
        "import operator",
        "from typing import Annotated, TypedDict",
        "",
        "from langgraph.graph import StateGraph, END",
        "from langchain_core.messages import BaseMessage, HumanMessage, AIMessage, SystemMessage",
    ]
    
    if has_tools:
        imports.append("from langgraph.prebuilt import ToolNode")
        imports.append("from langchain_core.tools import tool")

    # Providers
    if LLMProvider.OPENAI in used_providers:
        imports.append("from langchain_openai import ChatOpenAI")
    if LLMProvider.ANTHROPIC in used_providers:
        imports.append("from langchain_anthropic import ChatAnthropic")
    if LLMProvider.GOOGLE in used_providers:
        imports.append("from langchain_google_genai import ChatGoogleGenerativeAI")
    if LLMProvider.OLLAMA in used_providers:
        imports.append("from langchain_ollama import ChatOllama")

    # Tools
    if ToolName.TAVILY_SEARCH in used_tools:
        imports.append("from langchain_community.tools.tavily_search import TavilySearchResults")
    if ToolName.WIKIPEDIA in used_tools:
        imports.append("from langchain_community.tools.wikipedia import WikipediaQueryRun")
        imports.append("from langchain_community.utilities.wikipedia import WikipediaAPIWrapper")
    # For calculator or python_repl we'd import corresponding classes here if implemented
    
    return "\n".join(imports)


def _generate_state_schema() -> str:
    """Generate the AgentState class definition."""
    return (
        "class AgentState(TypedDict):\n"
        "    messages: Annotated[list[BaseMessage], operator.add]"
    )


def _generate_tools(nodes: list[NodeConfig]) -> tuple[str, dict[str, str]]:
    """Generate tool instantiations and return a mapping of node_id to tool variable."""
    tool_lines = []
    tool_vars = {}
    
    for node in nodes:
        if node.type == NodeType.TOOL and node.tool_name:
            var_name = f"tool_{_safe_id(node.id)}"
            tool_vars[node.id] = var_name
            
            if node.tool_name == ToolName.TAVILY_SEARCH:
                api_key = node.tool_api_key or ""
                tool_lines.append(f'{var_name} = TavilySearchResults(api_key="{api_key}", max_results=3)')
            elif node.tool_name == ToolName.WIKIPEDIA:
                tool_lines.append(f'{var_name}_api = WikipediaAPIWrapper()')
                tool_lines.append(f'{var_name} = WikipediaQueryRun(api_wrapper={var_name}_api)')
            # Default placeholder for other tools
            else:
                tool_lines.append(f'@tool\ndef {var_name}(query: str) -> str:\n    """Placeholder for {node.tool_name}"""\n    return "Result"')
                
    return "\n".join(tool_lines), tool_vars


def _generate_nodes(
    nodes: list[NodeConfig],
    llm_to_tools: dict[str, list[NodeConfig]],
    tool_vars: dict[str, str],
) -> str:
    """Generate node functions."""
    node_blocks = []
    
    for node in nodes:
        safe_id = _safe_id(node.id)
        
        if node.type == NodeType.LLM_AGENT:
            # Setup LLM instance
            llm_init = ""
            model = node.model or "gpt-4o"
            api_key = node.api_key or ""
            temp = node.temperature if node.temperature is not None else 0.7
            
            if node.provider == LLMProvider.OPENAI:
                llm_init = f'ChatOpenAI(model="{model}", api_key="{api_key}", temperature={temp})'
            elif node.provider == LLMProvider.ANTHROPIC:
                llm_init = f'ChatAnthropic(model="{model}", api_key="{api_key}", temperature={temp})'
            elif node.provider == LLMProvider.GOOGLE:
                llm_init = f'ChatGoogleGenerativeAI(model="{model}", api_key="{api_key}", temperature={temp})'
            elif node.provider == LLMProvider.OLLAMA:
                llm_init = f'ChatOllama(model="{model}", temperature={temp})'
            else:
                # Default to OpenAI if none specified
                llm_init = f'ChatOpenAI(model="{model}", api_key="{api_key}", temperature={temp})'
                
            connected_tools = llm_to_tools.get(node.id, [])
            sys_prompt = node.system_prompt or "You are a helpful assistant."
            
            block = [
                f"def {safe_id}_node(state: AgentState) -> dict:",
                f"    llm = {llm_init}",
            ]
            
            if connected_tools:
                tools_list = ", ".join(tool_vars[t.id] for t in connected_tools if t.id in tool_vars)
                if tools_list:
                    block.append(f"    llm_with_tools = llm.bind_tools([{tools_list}])")
                    block.append(f"    response = llm_with_tools.invoke([SystemMessage(content=\"\"\"{sys_prompt}\"\"\")] + state[\"messages\"])")
                else:
                    block.append(f"    response = llm.invoke([SystemMessage(content=\"\"\"{sys_prompt}\"\"\")] + state[\"messages\"])")
            else:
                block.append(f"    response = llm.invoke([SystemMessage(content=\"\"\"{sys_prompt}\"\"\")] + state[\"messages\"])")
                
            block.append("    return {\"messages\": [response]}")
            node_blocks.append("\n".join(block))
            
        elif node.type == NodeType.ROUTER:
            block = [
                f"def {safe_id}_router(state: AgentState) -> str:",
                '    """Conditional router — inspects last message and routes accordingly."""',
                '    messages = state.get("messages", [])',
                '    last_content = messages[-1].content if messages else ""',
            ]
            
            default_target = "END"
            if node.conditions:
                for cond in node.conditions:
                    target_safe = _safe_id(cond.target_node_id) if cond.target_node_id != "END" else "END"
                    block.append(f'    if "{cond.keyword}" in last_content:')
                    block.append(f'        return "{target_safe}"')
                    if cond.default_target_id:
                        default_target = _safe_id(cond.default_target_id) if cond.default_target_id != "END" else "END"
            
            block.append(f'    return "{default_target}"')
            node_blocks.append("\n".join(block))
            
    return "\n\n".join(node_blocks)


def _generate_graph_construction(
    nodes: list[NodeConfig],
    edges: list[EdgeConfig],
    node_in_edges: dict[str, list[str]],
    tool_vars: dict[str, str],
) -> str:
    """Generate the graph assembly logic."""
    lines = [
        "def build_graph() -> StateGraph:",
        "    graph = StateGraph(AgentState)",
        ""
    ]
    
    # Add nodes
    lines.append("    # Add nodes")
    for node in nodes:
        safe_id = _safe_id(node.id)
        if node.type == NodeType.LLM_AGENT:
            lines.append(f'    graph.add_node("{safe_id}", {safe_id}_node)')
        elif node.type == NodeType.TOOL:
            t_var = tool_vars.get(node.id)
            if t_var:
                lines.append(f'    graph.add_node("{safe_id}", ToolNode([{t_var}]))')
    lines.append("")
    
    # Determine entry point
    entry_point = "END"
    for edge in edges:
        if edge.source == "START":
            entry_point = _safe_id(edge.target)
            break
            
    # If no START edge, find a node with no incoming edges
    if entry_point == "END" and nodes:
        for node in nodes:
            if node.id not in node_in_edges and node.type != NodeType.TOOL:
                entry_point = _safe_id(node.id)
                break
        if entry_point == "END":
            entry_point = _safe_id(nodes[0].id)
            
    lines.append(f'    graph.set_entry_point("{entry_point}")')
    lines.append("")
    
    # Add edges
    lines.append("    # Add edges")
    routers = {n.id: n for n in nodes if n.type == NodeType.ROUTER}
    
    for edge in edges:
        if edge.source == "START" or edge.target == "START":
            continue
            
        src_safe = _safe_id(edge.source)
        tgt_safe = _safe_id(edge.target) if edge.target != "END" else "END"
        
        # If source is a router, skip it here, we handle it in conditional edges
        if edge.source in routers:
            continue
            
        # Tool node routing back to LLM automatically? Usually tools route back to their caller.
        # But here we stick to the explicit edges.
        lines.append(f'    graph.add_edge("{src_safe}", "{tgt_safe}")')
        
    lines.append("")
    
    # Add conditional edges for routers
    if routers:
        lines.append("    # Add conditional edges")
        for node_id, router in routers.items():
            safe_id = _safe_id(node_id)
            # Find incoming edges to this router
            # We need to attach the conditional edges to the nodes that feed into the router
            incoming = node_in_edges.get(node_id, [])
            
            # Identify mapping
            mapping = {}
            if router.conditions:
                for cond in router.conditions:
                    t_safe = _safe_id(cond.target_node_id) if cond.target_node_id != "END" else "END"
                    mapping[t_safe] = t_safe
                # Default mapping
                if router.conditions and router.conditions[0].default_target_id:
                    d_safe = _safe_id(router.conditions[0].default_target_id)
                    d_safe = d_safe if router.conditions[0].default_target_id != "END" else "END"
                    mapping[d_safe] = d_safe
                else:
                    mapping["END"] = "END"
            
            # Usually add_conditional_edges takes a source node.
            for inc in incoming:
                inc_safe = _safe_id(inc)
                mapping_str = ", ".join(f'"{k}": "{v}"' if v != "END" else f'"{k}": END' for k, v in mapping.items())
                lines.append(f'    graph.add_conditional_edges(')
                lines.append(f'        "{inc_safe}",')
                lines.append(f'        {safe_id}_router,')
                lines.append(f'        {{{mapping_str}}}')
                lines.append(f'    )')
                
    lines.append("")
    lines.append("    return graph.compile()")
    lines.append("")
    lines.append("app = build_graph()")
    
    return "\n".join(lines)


def _generate_main_block() -> str:
    """Generate the execution entry point block."""
    return (
        'if __name__ == "__main__":\n'
        '    result = app.invoke({"messages": [HumanMessage(content="Hello! What can you help me with?")]})\n'
        '    for message in result["messages"]:\n'
        '        print(f"{type(message).__name__}: {message.content}")'
    )
